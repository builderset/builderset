#!/usr/bin/env node
/**
 * Writes the reference pages that can come from the code, so they cannot
 * drift from it (step 16, part 3):
 *
 *   reference/email-blocks.mdx      createEmailRegistry() + the English locale
 *   reference/article-elements.mdx  createArticleRegistry() + the English locale
 *   reference/form-fields.mdx       createFormRegistry() + the English locale
 *   reference/issues.mdx            every issue code, with its message
 *   reference/css-variables.mdx     the public variables, from the theme's own files
 *   reference/props.mdx             every prop, from the tables in the packages' READMEs
 *
 *   node scripts/generate-reference.mjs           write them (the docs build runs this)
 *   node scripts/generate-reference.mjs --check   fail when one is out of date (pnpm test)
 *
 * It loads the BUILT kits (`pnpm build` first): what a project installs.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createArticleRegistry } from '@builderset/article';
import { en as articleEn } from '@builderset/article/locales/en';
import { createEmailRegistry } from '@builderset/email';
import { en as emailEn } from '@builderset/email/locales/en';
import { createFormRegistry } from '@builderset/form';
import { en as formEn } from '@builderset/form/locales/en';
import { TOKEN_NAMES, z } from '@builderset/engine';
import { en as engineEn } from '@builderset/engine/locales/en';

const DOCS = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(DOCS, '..', '..');
const OUT = join(DOCS, 'content', 'docs', 'reference');
const VERSION = JSON.parse(
  readFileSync(join(REPO, 'packages/engine/package.json'), 'utf8'),
).version;
const GENERATED = '{/* Generated by apps/docs/scripts/generate-reference.mjs — do not edit. */}';

/** Text for MDX outside code: braces and angle brackets would be read as JSX. */
const text = (value) => String(value).replace(/[{}<>]/g, (c) => `\\${c}`);
/** Inline code inside a table cell: a pipe would end the cell. */
const code = (value) => `\`${String(value).replace(/\|/g, '\\|')}\``;

function page(title, description, body) {
  // Quoted: a description with a colon is not valid YAML otherwise.
  return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${GENERATED}\n\n_Generated from Builderset ${VERSION}._\n\n${body.trim()}\n`;
}

// ── elements ───────────────────────────────────────────────────────────────

function typeOf(schema) {
  if (!schema || typeof schema !== 'object') return 'any';
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' · ');
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.anyOf || schema.oneOf) {
    return [...new Set((schema.anyOf ?? schema.oneOf).map(typeOf))].join(' or ');
  }
  if (schema.type === 'array') return `${typeOf(schema.items)}[]`;
  if (Array.isArray(schema.type)) return schema.type.join(' or ');
  return schema.type ?? 'object';
}

function shortJson(value) {
  if (value === undefined) return '';
  const json = JSON.stringify(value);
  return json.length > 48 ? `${json.slice(0, 45)}…` : json;
}

function placement(definition) {
  const parts = [];
  const rule = definition.container;
  if (rule) {
    if (rule.only) parts.push(`Holds only ${rule.only.map(code).join(', ')}`);
    else if (rule.except?.length)
      parts.push(`Holds any element but ${rule.except.map(code).join(', ')}`);
    else parts.push('Holds other elements');
    if (rule.min !== undefined || rule.max !== undefined) {
      parts.push(`${rule.min ?? 0} to ${rule.max ?? 'any number of'} children`);
    }
  }
  if (definition.parents) parts.push(`Only inside ${definition.parents.map(code).join(', ')}`);
  if (definition.internal) parts.push('Not in the insert menu');
  return parts.join('. ');
}

function elementsPage(registry, locale, kit) {
  const words = locale.elements ?? {};
  const categories = locale.categories ?? {};
  const byCategory = new Map();
  for (const definition of registry.all()) {
    const list = byCategory.get(definition.category) ?? [];
    list.push(definition);
    byCategory.set(definition.category, list);
  }
  const sections = [];
  for (const [category, definitions] of byCategory) {
    sections.push(`## ${text(categories[category] ?? category)}`);
    for (const definition of definitions) {
      const name = words[definition.type]?.name ?? definition.type;
      const description = words[definition.type]?.description;
      sections.push(`### ${text(name)}`);
      sections.push(
        [
          `${code(definition.type)} · version ${definition.version}`,
          description ? text(description) : null,
          placement(definition) || null,
        ]
          .filter(Boolean)
          .join(' — '),
      );
      let properties = {};
      try {
        properties = z.toJSONSchema(definition.schema, { unrepresentable: 'any' }).properties ?? {};
      } catch {
        properties = {};
      }
      const defaults = definition.defaults();
      const rows = Object.entries(properties).map(
        ([prop, schema]) =>
          `| ${code(prop)} | ${code(typeOf(schema))} | ${defaults[prop] === undefined ? '' : code(shortJson(defaults[prop]))} |`,
      );
      if (rows.length) {
        sections.push(['| Prop | Type | Default |', '| --- | --- | --- |', ...rows].join('\n'));
      } else {
        sections.push('No props.');
      }
    }
  }
  const total = registry.all().length;
  const { title, what, plural, factory } = KIT_PAGES[kit];
  return page(
    title,
    `Every ${what}: its type, where it may go, its props and their defaults.`,
    `${total} ${plural}, as \`${factory}()\` holds them. A prop's type is its JSON Schema type; the document stores exactly these props.\n\n${sections.join('\n\n')}`,
  );
}

/** How each kit's elements page names them. */
const KIT_PAGES = {
  email: {
    title: 'Email blocks',
    what: 'block of the email kit',
    plural: 'blocks',
    factory: 'createEmailRegistry',
  },
  article: {
    title: 'Article elements',
    what: 'element of the article kit',
    plural: 'elements',
    factory: 'createArticleRegistry',
  },
  form: {
    title: 'Form fields',
    what: 'field of the form kit',
    plural: 'fields',
    factory: 'createFormRegistry',
  },
};

// ── issues ─────────────────────────────────────────────────────────────────

function issuesPage() {
  const sources = [
    ['Every kit', engineEn.issueText ?? {}],
    ['Email', emailEn.workspace?.issueText ?? {}],
    ['Article', articleEn.workspace?.issueText ?? {}],
    ['Form', formEn.workspace?.issueText ?? {}],
  ];
  const rows = new Map();
  for (const [kit, messages] of sources) {
    for (const [codeName, message] of Object.entries(messages)) {
      const row = rows.get(codeName) ?? { message: String(message), kits: [] };
      row.kits.push(kit);
      rows.set(codeName, row);
    }
  }
  const table = [...rows]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([codeName, row]) => `| ${code(codeName)} | ${text(row.message)} | ${row.kits.join(', ')} |`,
    );
  return page(
    'Issues',
    'Every issue code the checkers report, in the browser and on the server, with the message a writer sees.',
    `The editor shows these to the writer; \`checkEmail\` and \`checkArticle\` return them, and so does the Python package — a server can answer with the same codes and the editor shows them in the same words. A draft may still carry the codes in \`DRAFT_TOLERATES\`; publishing refuses them all.\n\n| Code | Message | Kit |\n| --- | --- | --- |\n${table.join('\n')}`,
  );
}

// ── CSS variables ──────────────────────────────────────────────────────────

/** `light-dark(a, b)` → [a, b], splitting at the top-level comma only. */
function lightDark(value) {
  const inner = value
    .trim()
    .replace(/^light-dark\(/, '')
    .replace(/\)$/, '');
  let depth = 0;
  for (let i = 0; i < inner.length; i++) {
    if (inner[i] === '(') depth++;
    else if (inner[i] === ')') depth--;
    else if (inner[i] === ',' && depth === 0)
      return [inner.slice(0, i).trim(), inner.slice(i + 1).trim()];
  }
  return [inner, inner];
}

function cssVariablesPage() {
  const themeDir = join(REPO, 'packages', 'engine', 'src', 'theme');
  const defaultsCss = readFileSync(join(themeDir, 'defaults.css'), 'utf8');
  const themeCss = readFileSync(join(themeDir, 'theme.css'), 'utf8');
  const defaults = new Map(
    [...defaultsCss.matchAll(/--bst-d-([\w-]+):\s*([^;]+);/g)].map(([, n, v]) => [n, v.trim()]),
  );
  const rows = TOKEN_NAMES.map((name) => {
    const variable = `--builderset-${name}`;
    let light = '';
    let dark = '';
    if (defaults.has(name)) {
      [light, dark] = lightDark(defaults.get(name));
    } else {
      // Not a colour of its own: the fallback written where it is used.
      // `var(--builderset-x, fallback)`, which the formatter may wrap over lines.
      const found = new RegExp(`var\\(\\s*${variable}\\s*,`).exec(themeCss);
      const at = found ? found.index : -1;
      if (at !== -1) {
        let depth = 0;
        let end = at;
        for (let i = at; i < themeCss.length; i++) {
          if (themeCss[i] === '(') depth++;
          else if (themeCss[i] === ')' && --depth === 0) {
            end = i;
            break;
          }
        }
        const fallback = themeCss
          .slice(at + found[0].length, end)
          .replace(/\s+/g, ' ')
          .trim();
        light = dark = /var\(--|color-mix|light-dark/.test(fallback) ? 'derived' : fallback;
      }
    }
    const usedBy = [...themeCss.matchAll(/^\s*--([\w-]+):[^;]*?(?=;)/gms)]
      .filter(([line]) => line.includes(`${variable},`) || line.includes(`${variable})`))
      .map(([, internal]) => internal.replace(/^(color|radius|font|shadow|max-width)-/, ''));
    const cell = (value) => (value ? code(value) : '');
    return `| ${code(variable)} | ${cell(light)} | ${cell(dark === light ? '' : dark)} | ${[...new Set(usedBy)].map(code).join(', ')} |`;
  });
  return page(
    'CSS variables',
    "The editor's public theme: every --builderset-* variable, its light and dark default, and what it paints.",
    `${TOKEN_NAMES.length} variables. Set them in CSS on \`.builderset\` or an ancestor, or pass them as the \`tokens\` prop without the prefix. None has to be set. **derived** means the default is mixed from other variables — set it to use your own value. The internal names in the last column may change in any release; the variables will not.\n\n| Variable | Default (light) | Default (dark) | Paints |\n| --- | --- | --- | --- |\n${rows.join('\n')}`,
  );
}

// ── props ──────────────────────────────────────────────────────────────────

function propsPage() {
  const blocks = [];
  for (const kit of ['email', 'article', 'engine']) {
    const readme = readFileSync(join(REPO, 'packages', kit, 'README.md'), 'utf8');
    for (const [, file, components, table] of readme.matchAll(
      /<!-- props: ([^\s]+)((?: [\w]+)*) -->\n([\s\S]*?)<!-- \/props -->/g,
    )) {
      const where = components
        ? components.trim().split(' ').join(', ')
        : file.replace(/\.d\.ts$/, '');
      blocks.push(`## \`@builderset/${kit}\` — ${where}\n\n${table.trim()}`);
    }
  }
  return page(
    'Props',
    'Every prop of every exported component, as the published types declare them.',
    `Generated from the built type files (the same tables are in each package's README).\n\n${blocks.join('\n\n')}`,
  );
}

// ── write or check ─────────────────────────────────────────────────────────

const pages = {
  'email-blocks.mdx': elementsPage(createEmailRegistry(), emailEn, 'email'),
  'article-elements.mdx': elementsPage(createArticleRegistry(), articleEn, 'article'),
  'form-fields.mdx': elementsPage(createFormRegistry(), formEn, 'form'),
  'issues.mdx': issuesPage(),
  'css-variables.mdx': cssVariablesPage(),
  'props.mdx': propsPage(),
};

const check = process.argv.includes('--check');
const stale = [];
for (const [file, content] of Object.entries(pages)) {
  const path = join(OUT, file);
  let current = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    current = null;
  }
  if (current === content) continue;
  if (check) stale.push(file);
  else writeFileSync(path, content);
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run: node scripts/generate-reference.mjs`);
  process.exit(1);
}
console.log(
  check
    ? 'The reference pages are up to date.'
    : `Wrote ${Object.keys(pages).length} reference pages.`,
);
