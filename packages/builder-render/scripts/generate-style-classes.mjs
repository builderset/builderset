// Writes src/style-classes.ts: every style token × breakpoint range as a
// literal Tailwind class, because Tailwind only emits classes it finds written
// out in source. Run: node scripts/generate-style-classes.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const PREFIX = { all: '', desktop: 'lg:', tablet: 'sm:max-lg:', mobile: 'max-sm:' };
const SPACE = { none: '0', xs: '2', sm: '4', md: '6', lg: '10', xl: '16', '2xl': '24' };
const scale = (utility) =>
  Object.fromEntries(Object.entries(SPACE).map(([k, v]) => [k, `${utility}-${v}`]));

const PROPS = {
  marginTop: scale('mt'),
  marginBottom: scale('mb'),
  paddingX: scale('px'),
  paddingY: scale('py'),
  width: {
    auto: '',
    prose: 'max-w-[var(--maxw-prose,68ch)]',
    wide: 'max-w-5xl',
    full: 'w-full max-w-none',
  },
  align: { start: 'mr-auto', center: 'mx-auto', end: 'ml-auto' },
  textAlign: {
    start: 'text-start',
    center: 'text-center',
    end: 'text-end',
    justify: 'text-justify',
  },
  textColor: {
    default: '',
    muted: 'text-muted-foreground',
    primary: 'text-primary',
    inverted: 'text-background',
  },
  fontSize: { sm: 'text-sm', base: 'text-base', lg: 'text-lg', xl: 'text-xl' },
  background: {
    none: '',
    muted: 'bg-muted',
    card: 'bg-card',
    inverted: 'bg-foreground text-background',
    primary: 'bg-primary text-primary-foreground',
  },
  borderWidth: { none: 'border-0', thin: 'border', thick: 'border-2' },
  borderColor: {
    default: 'border-border',
    strong: 'border-border-strong',
    primary: 'border-primary',
  },
  radius: {
    none: 'rounded-none',
    sm: 'rounded-[var(--radius-control,0.4rem)]',
    md: 'rounded-[var(--radius-card,0.625rem)]',
    lg: 'rounded-2xl',
    full: 'rounded-full',
  },
  shadow: { none: 'shadow-none', sm: 'shadow-sm', md: 'shadow-md', lg: 'shadow-xl' },
  hidden: { true: 'hidden' },
};

const prefix = (p, cls) =>
  cls
    ? cls
        .split(' ')
        .map((c) => p + c)
        .join(' ')
    : '';
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`);

const lines = [
  '/**',
  ' * Style tokens → Tailwind classes, per breakpoint range. GENERATED by',
  ' * `scripts/generate-style-classes.mjs` — every class is written out as a',
  ' * literal because Tailwind only emits the classes it can find in source; a',
  ' * class assembled from parts at runtime would render as nothing.',
  ' *',
  ' * Ranges: `all` (no prefix), `desktop` (lg and up), `tablet` (sm up to lg),',
  ' * `mobile` (below sm).',
  ' */',
  '',
  'export const STYLE_CLASSES = {',
];
for (const [name, values] of Object.entries(PROPS)) {
  lines.push(`  ${name}: {`);
  for (const [range, p] of Object.entries(PREFIX)) {
    lines.push(`    ${range}: {`);
    for (const [k, v] of Object.entries(values)) lines.push(`      ${key(k)}: '${prefix(p, v)}',`);
    lines.push('    },');
  }
  lines.push('  },');
}
lines.push('} as const;', '');
writeFileSync(fileURLToPath(new URL('../src/style-classes.ts', import.meta.url)), lines.join('\n'));
