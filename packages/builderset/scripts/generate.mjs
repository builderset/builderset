#!/usr/bin/env node
/**
 * Writes src/: one re-export file per door of every kit
 * (docs/plan/steps/11_ALL_IN_ONE_PACKAGE.md, part 2). Run after the kits are
 * built — it reads their type files:
 *
 *   node scripts/generate.mjs           write the files
 *   node scripts/generate.mjs --check   exit 1 if a committed file is stale
 *
 * Named exports only, never `export *`: a client door starts with
 * 'use client', and Next.js refuses `export *` in a client boundary. Types are
 * re-exported with `export type`.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const HERE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGES = resolve(HERE, '..');
const ts = createRequire(join(HERE, 'package.json'))('typescript');

/** kit → door → [the built type file under the kit's dist/, is it a client door]. */
const DOORS = {
  engine: {
    index: ['core/index.d.ts', false],
    host: ['host/index.d.ts', false],
    editor: ['editor/index.d.ts', true],
    ui: ['editor/ui/index.d.ts', true],
  },
  email: {
    index: ['core/index.d.ts', false],
    render: ['render/index.d.ts', false],
    host: ['host.d.ts', false],
    editor: ['editor/index.d.ts', true],
  },
  article: {
    index: ['core/index.d.ts', false],
    render: ['render/index.d.ts', false],
    host: ['host.d.ts', false],
    editor: ['editor/index.d.ts', true],
  },
  form: {
    index: ['core/index.d.ts', false],
    render: ['render/index.d.ts', true],
    host: ['host.d.ts', false],
    editor: ['editor/index.d.ts', true],
  },
  // A card renders anywhere — a page, a print sheet, a server: no client door.
  card: {
    index: ['core/index.d.ts', false],
    render: ['render/index.d.ts', false],
    host: ['host.d.ts', false],
    editor: ['editor/index.d.ts', true],
  },
  // The popup's render door is the working popup, with its own state: a client door.
  popup: {
    index: ['core/index.d.ts', false],
    render: ['render/index.d.ts', true],
    host: ['host.d.ts', false],
    editor: ['editor/index.d.ts', true],
  },
};

const specifier = (kit, door) => `@builderset/${kit}${door === 'index' ? '' : `/${door}`}`;
const byName = (a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }) || a.localeCompare(b);

/** The value and type names a built type file exports. */
/** One TypeScript program for every type file, so the kits are read once. */
function exportReader(files) {
  const program = ts.createProgram(files, {
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    target: ts.ScriptTarget.ES2023,
    jsx: ts.JsxEmit.ReactJSX,
    skipLibCheck: true,
    noEmit: true,
  });
  const checker = program.getTypeChecker();
  return (file) => {
    const source = program.getSourceFile(file);
    if (!source) throw new Error(`${file} does not exist: build the kits first`);
    const values = [];
    const types = [];
    for (const symbol of checker.getExportsOfModule(checker.getSymbolAtLocation(source))) {
      const target =
        symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
      (target.flags & ts.SymbolFlags.Value ? values : types).push(symbol.getName());
    }
    return { values: values.sort(byName), types: types.sort(byName) };
  };
}

function reExport(from, { values, types }, client) {
  const list = (names) => names.map((n) => `  ${n},`).join('\n');
  const lines = [`// Generated by scripts/generate.mjs from ${from}. Do not edit.`];
  if (client) lines.push(`'use client';`);
  if (values.length) lines.push('', `export {\n${list(values)}\n} from '${from}';`);
  if (types.length) lines.push('', `export type {\n${list(types)}\n} from '${from}';`);
  return `${lines.join('\n')}\n`;
}

/** Every file this package's src/ should hold, generated and formatted. */
export async function generated() {
  // Every door: [path under src/, the module it re-exports, its type file, client?].
  const doors = [];
  for (const [kit, kitDoors] of Object.entries(DOORS)) {
    const dist = join(PACKAGES, kit, 'dist');
    for (const [door, [typeFile, client]] of Object.entries(kitDoors))
      doors.push([`${kit}/${door}.ts`, specifier(kit, door), join(dist, typeFile), client]);
    // Each kit's languages under the kit's name: the kits' locale objects have
    // the same keys with different words ('Activate' and 'Publish'), so they
    // are kept apart rather than merged.
    for (const name of readdirSync(join(dist, 'locales')).filter((n) => n.endsWith('.d.ts'))) {
      const code = name.replace(/\.d\.ts$/, '');
      doors.push([
        `${kit}/locales/${code}.ts`,
        `@builderset/${kit}/locales/${code}`,
        join(dist, 'locales', name),
        false,
      ]);
    }
  }
  const exportsOf = exportReader(doors.map(([, , typeFile]) => typeFile));
  const files = new Map();
  for (const [path, from, typeFile, client] of doors)
    files.set(path, reExport(from, exportsOf(typeFile), client));
  const config = await prettier.resolveConfig(join(HERE, 'src', 'x.ts'));
  for (const [path, text] of files)
    files.set(path, await prettier.format(text, { ...config, filepath: join(HERE, 'src', path) }));
  return files;
}

const check = process.argv.includes('--check');
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let stale = 0;
  for (const [path, text] of await generated()) {
    const file = join(HERE, 'src', path);
    const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === text) continue;
    stale += 1;
    if (check) console.log(`stale: src/${path}`);
    else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
  if (check && stale) {
    console.log('Run: node scripts/generate.mjs');
    process.exit(1);
  }
  if (!check) console.log(`${stale} files written`);
}
